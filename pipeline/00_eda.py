def ward_of(lat, lon):
    pt = Point(lon, lat)
    for k, g in ward_poly.items():
        if g.contains(pt):
            return k
    for k, g in ward_poly.items():
        if g.touches(pt) or g.distance(pt) < 1e-9:
            return k
    return None


