DEV = re.compile(r"[\u0900-\u097F]")


def norm(s):
    s = unicodedata.normalize("NFC", str(s)).lower()
    s = re.sub(r"[’'`\.\(\)]", "", s)
    s = re.sub(r"\s+", " ", s).strip()
    return s


