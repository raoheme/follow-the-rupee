for r in loc.itertuples():
    for key in [r.locality] + ([a.strip() for a in str(r.aliases).split(";") if a.strip()] if isinstance(r.aliases, str) else []):
        k = norm(key)
        if k in gaz and gaz[k][3] != r.locality:
            amb_alias.add(k)
        gaz[k] = (r.ward_code, r.lat, r.lon, r.locality)
