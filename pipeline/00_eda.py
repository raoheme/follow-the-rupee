def find_loc(text):
    t = norm(text)
    ms = [m.group(1) for m in gk_re.finditer(t)]
    return sorted(set(gaz[m][3] for m in ms)), ms


def loc_lookup(r):
    """locality_text exact/alias first, then description scan."""
    k = norm(r.locality_text) if isinstance(r.locality_text, str) else ""
    if k in gaz:
        return gaz[k], "locality_text_exact"
    names, ms = find_loc(r.locality_text if isinstance(r.locality_text, str) else "")
    if len(names) == 1:
        return gaz[norm(ms[0])], "locality_text_contains"
    names, ms = find_loc(r.description)
    if len(names) == 1:
        return gaz[norm(ms[0])], "description_scan"
    if len(names) > 1:
        wards_ = {gaz[norm(m)][0] for m in ms}
        if len(wards_) == 1:
            return gaz[norm(ms[0])], "description_scan_samewards"
    return None, "unresolved"


